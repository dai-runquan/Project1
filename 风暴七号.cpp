#include <iostream>  // 包含输入输出流头文件
#include <string>    // 包含字符串处理头文件
int main() {  // 主函数入口
    std::cout << -7 / -6 << '\n';
    std::cout << -7 / 6 << '\n';
    std::cout << 7 / -6 << '\n';
    std::cout << 7 / 6 << '\n';
    int a;  // 声明整型变量a，用于存储用户输入
    while (true) {  // 添加无限循环，直到用户输入正确的三位数
        std::cout << "请输入一个三位整数：\n";  // 输出提示信息

        // 检查输入是否成功（用户是否输入了数字）
        if (!(std::cin >> a)) {  // 如果输入失败（如输入了字母等非数字字符）
            std::cout << "错误：请输入有效的数字\n";  // 输出错误信息
            std::cin.clear(); // 清除输入流的错误状态标志
            std::cin.ignore(10000, '\n'); // 忽略缓冲区中最多10000个字符，直到遇到换行符
            continue;  // 跳过本次循环的剩余部分，重新开始循环
        }

        // 验证输入的数字是否为三位数
        if (a < 100 || a > 999) {  // 如果数字小于100或大于999
            std::cout << "错误：请输入一个三位整数（100-999）\n";  // 输出范围错误信息
            continue;  // 跳过本次循环的剩余部分，重新开始循环
        }

        break;  // 如果输入正确，跳出循环
    }

    // 分解三位数的各个位
    int o, p, q;  // 声明三个整型变量，分别存储百位、十位和个位
    o = a / 100;  // 计算百位数（整除100）
    p = a / 10 % 10;  // 计算十位数（先整除10，再对10取余）
    q = a % 10;  // 计算个位数（对10取余）

    // 输出反转后的数字
    std::cout << "反转后的数字：" << q * 100 + p * 10 + o << '\n';  // 重新组合并输出
	int year;  // 声明整型变量year，用于存储用户输入的年份
	std::cout << "请输入一个年份：\n";  // 输出提示信息
	std::cin >> year;  // 从标准输入读取年份
    if ((year % 4 == 0 and year % 100 != 0) or (year % 400 == 0)) {  // 判断是否为闰年
		std::cout << year << "是闰年\n";  // 输出闰年信息
	}
	else {
		std::cout << year << "不是闰年\n";  // 输出非闰年信息
    }
    system("pause");  // 暂停程序，等待用户按键
    return 0;
} // 返回0，表示程序正常结束